#!/usr/bin/env python3
"""Generate the lightning-charge assets from tools/glyphs.json (see capture_glyphs.py).

    python tools/gen_charge.py

Writes into src/animations/:
  charge_<preset>_<glyph>.anim   one fade per clock glyph (0-9 and c for the colon) and clock colour, 24 s at 10 fps,
                                 shaped like the glyph. Sections t0..t23 start at each second and all run to the end,
                                 so a redraw (new minute, a bat) can resume the fade where it was.
  glowcharge.anim                the haze behind the time turning green too, 2 fps, sections g0..g7 every 3 s (the glow
                                 breathes with a 3 s period, so each section starts in phase with the scene redraw).
and src/app/glyphs.ts (the glyph metrics the app lays the time out with).
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from charge_model import (CHARGE_FPS, CHARGE_SECONDS, GLOW_FPS, GLOW_ORANGE, PRESETS, charge_color,  # noqa: E402
                          fade_u, glow_level)
from make_anim import write_anim  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "animations"
STEP = 6          # colour steps: repeated frames cost almost nothing
TOTAL = int(CHARGE_SECONDS * CHARGE_FPS)


def name(ch):
    return "c" if ch == ":" else ch


def glyph_anim(preset, ch, g):
    w, h = g["w"], g["h"]
    frames = []
    for i in range(TOTAL):
        c = tuple(min(255, round(v / STEP) * STEP) for v in charge_color(i / CHARGE_FPS, PRESETS[preset]))
        px = bytearray()
        for row in g["mask"]:
            for cell in row:
                px += bytes((c[2], c[1], c[0], 255)) if cell == "#" else bytes(4)
        frames.append(bytes(px))
    sections = [(f"t{k}", k * CHARGE_FPS, TOTAL - 1) for k in range(int(CHARGE_SECONDS))]
    path = OUT / f"charge_{preset}_{name(ch)}.anim"
    write_anim(path, frames, w, h, CHARGE_FPS, sections)
    return path.stat().st_size


def glow_anim():
    x0, x1, y0, y1 = 19, 54, 0, 13   # keeps clear of the pumpkin, the tombstones and the grass
    w, h = x1 - x0 + 1, y1 - y0 + 1
    pix = [(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)
           if max(glow_level(x + 0.5, y + 0.5, f) for f in (0, 30)) > 0.02]
    total = int(CHARGE_SECONDS * GLOW_FPS)
    per_section = 3 * GLOW_FPS            # 3 s = one breath
    frames = []
    for i in range(total):
        t = i / GLOW_FPS
        c = tuple(round(v / 8) * 8 for v in charge_color(t, GLOW_ORANGE))
        boost = 1.0 + 0.8 * (1.0 - fade_u(t))          # brighter while green, so the colour change shows
        f = (i % per_section) / GLOW_FPS * 20          # the breathing restarts with the scene at every redraw
        buf = bytearray(w * h * 4)
        for x, y in pix:
            lvl = glow_level(x + 0.5, y + 0.5, f) * boost
            o = ((y - y0) * w + (x - x0)) * 4
            buf[o:o + 4] = bytes((min(255, round(c[2] * lvl)), min(255, round(c[1] * lvl)), min(255, round(c[0] * lvl)), 255))
        frames.append(bytes(buf))
    sections = [(f"g{k}", k * per_section, total - 1) for k in range(total // per_section)]
    path = OUT / "glowcharge.anim"
    write_anim(path, frames, w, h, GLOW_FPS, sections)
    return path.stat().st_size, (x0, y0, w, h)


def main():
    data = json.loads((Path(__file__).resolve().parent / "glyphs.json").read_text())
    total = 0
    for preset in PRESETS:
        for ch, g in data["glyphs"].items():
            total += glyph_anim(preset, ch, g)
        print(f"{preset}: done")
    size, (gx, gy, gw, gh) = glow_anim()
    total += size
    print(f"glowcharge {size} bytes; charge assets {total / 1024:.0f} KB")
    glyphs = ",\n".join(f'  "{ch}": [{g["ox"]}, {g["oy"]}, {g["w"]}, {g["h"]}]' for ch, g in data["glyphs"].items())
    presets = ",\n".join(f'  {k}: [{v[0]}, {v[1]}, {v[2]}]' for k, v in PRESETS.items())
    (ROOT / "src" / "app" / "glyphs.ts").write_text(f"""// Generated by tools/gen_charge.py from tools/glyphs.json - do not edit.

/** extra_large glyph ink as measured on the bar: [offset x, offset y, width, height] from the text element's top-left. */
export const GLYPHS: Record<string, [number, number, number, number]> = {{
{glyphs},
}};

/** Blank columns between two glyphs' ink. */
export const GAP = {data["gap"]};

/** First ink row of the digits (the single centred element used to put it on row 3). */
export const INK_TOP = {data["ink_top"]};

/** The glow charge overlay: its position and size. */
export const GLOW = {{ x: {gx}, y: {gy}, w: {gw}, h: {gh} }};

/** The clock colours that have charge assets (RGB). */
export const PRESET_RGB: Record<string, [number, number, number]> = {{
{presets},
}};
""")


if __name__ == "__main__":
    main()
